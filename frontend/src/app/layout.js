import "./globals.css";

export const metadata = {
  title: "TrustShare - Intelligent Encrypted File Sharing & Digital Collaboration Platform",
  description: "Enterprise-grade AES-256 encrypted file sharing and collaboration platform",
};

export default function RootLayout({ children }) {
  return (
    <html lang="en" className="h-full antialiased" suppressHydrationWarning>
      <head>
        <script
          dangerouslySetInnerHTML={{
            __html: `
              (function() {
                try {
                  const storedTheme = localStorage.getItem('trustshare_theme');
                  const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
                  if (storedTheme === 'dark' || (!storedTheme && prefersDark)) {
                    document.documentElement.classList.add('dark');
                  } else {
                    document.documentElement.classList.remove('dark');
                  }
                } catch (e) {}
              })();
            `
          }}
        />
      </head>
      <body className="min-h-full flex flex-col font-sans transition-colors duration-200">{children}</body>
    </html>
  );
}
